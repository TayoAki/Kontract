// Builds src/lib/api-v1.ts: the engine API's response types as one
// self-contained file another server (Magpie) can copy to type its client.
// The declarations are copied from the real source, with everything they
// reference, so they can't drift: `npm test` fails when the file is stale.
//
//   node --experimental-strip-types scripts/api-v1-types.ts         rewrite it
//   node --experimental-strip-types scripts/api-v1-types.ts --check exit 1 if stale

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const OUT = `${ROOT}src/lib/api-v1.ts`;

const SOURCES = ["types", "places", "pricing-stats", "permits", "site-facts", "sled", "permit-trades", "claude", "service-usage"].map((f) => `${ROOT}src/lib/${f}.ts`);

// What the v1 responses return; everything these reference comes along.
const ROOTS = [
  "Opportunity",
  "OpportunityResults",
  "BidDetails",
  "Breakdown",
  "PricingResults",
  "RecipientSummary",
  "SubSearchResult",
  "PermitResults",
  "PermitSearchResults",
  "PermitContractor",
  "Deal",
  "CompanyProfile",
  "SiteFacts",
  "FeedWithHealth",
  "BidFeedWithHealth",
  "PermitMarketInfo",
  "Trade",
  "Work",
  "DraftEvent",
  "Usage",
];

const HEADER = `// Kontract engine API (/api/v1) types. GENERATED by scripts/api-v1-types.ts
// from the source; don't edit by hand. Changes are additive only: removing or
// renaming a field means /api/v2. Copy this one file to type a client.
//
// Every call needs \`Authorization: Bearer <service key>\` and
// \`X-Workspace-Id: <a-z0-9->\` (except GET /api/v1/health). Paid calls report
// what they cost in the \`X-Kontract-Cost-Micro\` header (millionths of a
// dollar); a draft stream reports it in its final "done" event instead.
// Errors are \`{ error: string }\` with a 4xx or 5xx status.

export interface ErrorResponse {
  error: string;
}

/** GET /api/v1/health (no key). */
export interface HealthResponse {
  ok: boolean;
  samAsOf: string | null;
  notices: number;
  sledBids: number;
  permitFeeds: { ok: number; failing: number };
}

/** GET /api/v1/opportunities: OpportunityResults, without descriptions. */
export type OpportunitiesResponse = OpportunityResults;

/** GET /api/v1/opportunities/:id */
export interface OpportunityResponse {
  opportunity: Opportunity;
}

/** POST /api/v1/opportunities/:id/details { claude?: boolean, opportunity?: Opportunity } */
export interface DetailsResponse {
  details: BidDetails;
}

/** POST /api/v1/opportunities/:id/breakdown { opportunity?: Opportunity } */
export interface BreakdownResponse {
  breakdown: Breakdown;
  source: "claude" | "rules";
}

/** POST /api/v1/pricing { query: PricingQuery, context?: { agency?, state? } } */
export interface PricingResponse extends PricingResults {
  recipients: RecipientSummary[];
}

/** POST /api/v1/subcontractors { query, location } */
export type SubcontractorsResponse = SubSearchResult;

/** POST /api/v1/websites/read { url } */
export interface WebsiteResponse {
  facts: SiteFacts;
}

/** GET /api/v1/permits (the query params of /api/permits) */
export type PermitsResponse = PermitSearchResults;

/** GET /api/v1/permits/contractors?state=&city=&work= */
export type PermitContractorsResponse = PermitContractor[];

/** GET /api/v1/sources */
export interface SourcesResponse {
  states: { code: string; name: string; markets: number }[];
  markets: PermitMarketInfo[];
  feeds: FeedWithHealth[];
  bidFeeds: BidFeedWithHealth[];
  trades: Trade[];
  work: Work[];
}

/** POST /api/v1/drafts streams one of these per line (NDJSON). */
export type DraftStreamEvent = { type: "meta"; source: "claude" | "template" } | DraftEvent | { type: "done"; costMicro: number };

/** GET /api/v1/usage?workspace=&month=YYYY-MM */
export type UsageResponse = Usage;
`;

interface Decl {
  name: string;
  text: string;
}

/** Top-level `export interface` / `export type` declarations, with the doc comment above each. */
function declarations(source: string): Decl[] {
  const lines = source.split("\n");
  const out: Decl[] = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^export (interface|type) (\w+)/.exec(lines[i]!);
    if (!m) continue;
    let start = i;
    if (lines[i - 1]?.trimEnd().endsWith("*/")) {
      start = i - 1;
      while (start > 0 && !lines[start]!.trimStart().startsWith("/**")) start--;
    }
    let end = i;
    if (m[1] === "interface") {
      while (end < lines.length && lines[end] !== "}") end++;
    } else {
      // A type alias ends at the first ";" outside brackets.
      let depth = 0;
      outer: for (; end < lines.length; end++) {
        for (const ch of lines[end]!) {
          if ("{([<".includes(ch)) depth++;
          else if ("})]>".includes(ch)) depth--;
          else if (ch === ";" && depth <= 0) break outer;
        }
      }
    }
    out.push({ name: m[2]!, text: lines.slice(start, end + 1).join("\n") });
    i = end;
  }
  return out;
}

export function generate(): string {
  const all = new Map<string, Decl>();
  for (const file of SOURCES) for (const d of declarations(readFileSync(file, "utf8"))) if (!all.has(d.name)) all.set(d.name, d);
  const picked = new Set<string>();
  const queue = [...ROOTS];
  while (queue.length) {
    const name = queue.shift()!;
    if (picked.has(name)) continue;
    const d = all.get(name);
    if (!d) throw new Error(`api-v1-types: no exported declaration for ${name}`);
    picked.add(name);
    for (const ref of d.text.replace(/\/\*[\s\S]*?\*\/|\/\/.*$/gm, "").match(/\b[A-Z]\w*\b/g) ?? []) if (all.has(ref) && !picked.has(ref)) queue.push(ref);
  }
  const body = [...picked].sort().map((n) => all.get(n)!.text).join("\n\n");
  return `${HEADER}\n${body}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = generate();
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== next) {
      console.error("src/lib/api-v1.ts is stale; run: node --experimental-strip-types scripts/api-v1-types.ts");
      process.exit(1);
    }
  } else writeFileSync(OUT, next);
}
